import { TOPIC_TRANSLATIONS_ID } from "./topicTranslations";

export function getLocalizedTopic(topic: Topic, lang: "id" | "en" = "en"): Topic {
  if (lang !== "id") return topic;
  const trans = TOPIC_TRANSLATIONS_ID[topic.id];
  if (!trans) return topic;

  return {
    ...topic,
    title: trans.title,
    tagline: trans.tagline,
    category: trans.category as Topic["category"],
    difficulty: trans.difficulty as Topic["difficulty"],
    readTime: trans.readTime,
    levels: topic.levels.map((lvl) => {
      const transLvl = trans.levels.find((l) => l.level === lvl.level);
      if (!transLvl) return lvl;
      return {
        ...lvl,
        name: transLvl.name as Topic["levels"][0]["name"],
        audience: transLvl.audience,
        summary: transLvl.summary,
        keyConcepts: transLvl.keyConcepts,
        markdownContent: transLvl.markdownContent,
      };
    }),
    simulationSteps: topic.simulationSteps.map((step) => {
      const transStep = trans.simulationSteps?.find((s) => s.stepNumber === step.stepNumber);
      if (!transStep) return step;
      return {
        ...step,
        title: transStep.title,
        shortDesc: transStep.shortDesc,
        details: transStep.details,
      };
    }),
    challenge: {
      ...topic.challenge,
      question: trans.challenge.question,
      options: trans.challenge.options,
      explanation: trans.challenge.explanation,
    },
  };
}

export function getTopicBySlug(slug: string, lang: "id" | "en" = "en"): Topic | undefined {
  const raw = TOPICS.find((t) => t.slug === slug || t.id === slug);
  if (!raw) return undefined;
  return getLocalizedTopic(raw, lang);
}

export function getTopicsByCategory(categorySlug: string, lang: "id" | "en" = "en"): Topic[] {
  const list = categorySlug === "all" ? TOPICS : TOPICS.filter((t) => t.categorySlug === categorySlug);
  return list.map((t) => getLocalizedTopic(t, lang));
}
